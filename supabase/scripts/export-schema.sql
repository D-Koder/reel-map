-- READ-ONLY. Run in the LIVE project's SQL editor. It changes nothing: it writes out the app's
-- database structure (tables, functions, security rules, triggers) as one block of SQL, with no data.
-- Copy the single result cell and run it in the TEST project's SQL editor to build an exact copy.
--
-- Left out on purpose:
--   * every row of data (no users, places or keys)
--   * functions that call out to the internet (net.http_post), e.g. the push sender. They hold the
--     live project's address and secret, and a test project must never push through live.
--   * scheduled jobs (pg_cron)
with
our_schemas as (
  select oid, nspname from pg_namespace where nspname in ('public', 'private')
),
ext_objects as (
  select objid from pg_depend where deptype = 'e'
),
fns as (
  select p.oid, n.nspname, p.proname, pg_get_functiondef(p.oid) as def
  from pg_proc p
  join our_schemas n on n.oid = p.pronamespace
  where p.prokind in ('f', 'p')
    and p.oid not in (select objid from ext_objects)
),
skipped_fns as (
  select oid from fns where def ilike '%http_post%' or def ilike '%bearer %'
),
tabs as (
  select c.oid, n.nspname, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.relreplident, c.relacl
  from pg_class c
  join our_schemas n on n.oid = c.relnamespace
  where c.relkind in ('r', 'p', 'v')
    and c.oid not in (select objid from ext_objects)
),
cols as (
  select t.oid as reloid, t.nspname, t.relname, a.attnum, a.attname, a.attnotnull, a.attidentity, a.attgenerated,
         format_type(a.atttypid, a.atttypmod) as typ, pg_get_expr(d.adbin, d.adrelid) as def
  from tabs t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where t.relkind in ('r', 'p')
),
stmts(ord, sort, stmt) as (
  select 0, '', 'set check_function_bodies = off;'
  union all
  select 0, 'skipped', '-- Left out (they call the internet): '
         || coalesce((select string_agg(f.nspname || '.' || f.proname, ', ') from fns f where f.oid in (select oid from skipped_fns)), 'nothing')
  union all
  select 1, 'private', 'create schema if not exists private;'
  union all
  -- Extensions the app relies on (others come with every Supabase project).
  select 2, e.extname, format('create extension if not exists %I with schema extensions;', e.extname)
  from pg_extension e where e.extname in ('pgcrypto', 'uuid-ossp', 'pg_trgm', 'citext', 'unaccent', 'moddatetime')
  union all
  -- Enum types.
  select 3, n.nspname || '.' || t.typname,
         format('create type %I.%I as enum (%s);', n.nspname, t.typname,
                (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid = t.oid))
  from pg_type t join our_schemas n on n.oid = t.typnamespace
  where t.typtype = 'e' and t.oid not in (select objid from ext_objects)
  union all
  -- Sequences that aren't identity columns.
  select 4, n.nspname || '.' || c.relname, format('create sequence if not exists %I.%I;', n.nspname, c.relname)
  from pg_class c join our_schemas n on n.oid = c.relnamespace
  where c.relkind = 'S' and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
  union all
  -- Tables: columns, types, not null, identity and generated columns. Defaults come later.
  select 5, nspname || '.' || relname,
         format('create table if not exists %I.%I (%s);', nspname, relname,
                string_agg(format('%I %s%s%s', attname, typ,
                  case attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end
                  || case when attgenerated = 's' then format(' generated always as (%s) stored', def) else '' end,
                  case when attnotnull then ' not null' else '' end), ', ' order by attnum))
  from cols group by reloid, nspname, relname
  union all
  -- Functions (bodies aren't checked until they run, so the order doesn't matter).
  select 6, nspname || '.' || proname || oid::text, def || ';'
  from fns where oid not in (select oid from skipped_fns)
  union all
  -- Column defaults (after functions, since some defaults call them).
  select 7, nspname || '.' || relname || '.' || attname,
         format('alter table %I.%I alter column %I set default %s;', nspname, relname, attname, def)
  from cols where def is not null and attidentity = '' and attgenerated = ''
  union all
  -- Keys and checks, then foreign keys.
  select case when con.contype = 'f' then 9 else 8 end, t.nspname || '.' || t.relname || '.' || con.conname,
         format('alter table %I.%I add constraint %I %s;', t.nspname, t.relname, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con join tabs t on t.oid = con.conrelid
  where con.contype in ('p', 'u', 'c', 'x', 'f')
  union all
  -- Indexes that aren't part of a key.
  select 10, t.nspname || '.' || ic.relname, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join tabs t on t.oid = i.indrelid join pg_class ic on ic.oid = i.indexrelid
  where not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
  union all
  -- Views.
  select 11, t.nspname || '.' || t.relname,
         format('create or replace view %I.%I%s as %s', t.nspname, t.relname,
                coalesce(' with (' || array_to_string(c.reloptions, ', ') || ')', ''),
                pg_get_viewdef(t.oid))
  from tabs t join pg_class c on c.oid = t.oid where t.relkind = 'v'
  union all
  -- Triggers, including the one on auth.users that sets up new accounts.
  select 12, c.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg join pg_class c on c.oid = tg.tgrelid
  where not tg.tgisinternal
    and tg.tgfoid in (select oid from fns)
    and tg.tgfoid not in (select oid from skipped_fns)
  union all
  -- Row level security.
  select 13, nspname || '.' || relname,
         format('alter table %I.%I enable row level security;', nspname, relname)
         || case when relforcerowsecurity then format(' alter table %I.%I force row level security;', nspname, relname) else '' end
  from tabs where relrowsecurity
  union all
  -- Security rules (policies), including the ones on uploaded photos.
  select 14, p.schemaname || '.' || p.tablename || '.' || p.policyname,
         format('create policy %I on %I.%I as %s for %s to %s%s%s;', p.policyname, p.schemaname, p.tablename,
                p.permissive, p.cmd,
                (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(p.roles) r),
                coalesce(' using (' || p.qual || ')', ''), coalesce(' with check (' || p.with_check || ')', ''))
  from pg_policies p
  where p.schemaname in ('public', 'private')
     or (p.schemaname = 'storage' and p.tablename = 'objects')
  union all
  -- Who may use each table: start from nothing, then grant what live grants.
  select 15, t.nspname || '.' || t.relname,
         format('revoke all on %I.%I from anon, authenticated;', t.nspname, t.relname)
         || coalesce(' ' || (
           select string_agg(format('grant %s on %I.%I to %s;', acl.privilege_type, t.nspname, t.relname,
                                    case when acl.grantee = 0 then 'public' else quote_ident(r.rolname) end), ' ')
           from aclexplode(t.relacl) acl left join pg_roles r on r.oid = acl.grantee
           where acl.grantee = 0 or r.rolname in ('anon', 'authenticated', 'service_role')), '')
  from tabs t where t.relacl is not null
  union all
  -- Who may call each function.
  select 16, f.nspname || '.' || f.proname || f.oid::text,
         format('revoke all on function %s from public, anon, authenticated;', f.oid::regprocedure)
         || coalesce(' ' || (
           select string_agg(format('grant execute on function %s to %s;', f.oid::regprocedure,
                                    case when acl.grantee = 0 then 'public' else quote_ident(r.rolname) end), ' ')
           from pg_proc p, aclexplode(p.proacl) acl left join pg_roles r on r.oid = acl.grantee
           where p.oid = f.oid and (acl.grantee = 0 or r.rolname in ('anon', 'authenticated', 'service_role'))), '')
  from fns f where f.oid not in (select oid from skipped_fns)
    and (select proacl from pg_proc where oid = f.oid) is not null
  union all
  -- Live updates.
  select 17, nspname || '.' || relname, format('alter table %I.%I replica identity full;', nspname, relname)
  from tabs where relreplident = 'f'
  union all
  select 18, pt.schemaname || '.' || pt.tablename,
         format('alter publication supabase_realtime add table %I.%I;', pt.schemaname, pt.tablename)
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime' and pt.schemaname in ('public', 'private')
  union all
  -- Photo buckets (settings only, no files).
  select 19, b.id,
         format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %s, %L) on conflict (id) do nothing;',
                b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'null'), b.allowed_mime_types)
  from storage.buckets b
)
select '-- Reel Map database structure, exported ' || now()::date || E'. No data.\n\n'
       || string_agg(stmt, E'\n\n' order by ord, sort) as sql
from stmts;
